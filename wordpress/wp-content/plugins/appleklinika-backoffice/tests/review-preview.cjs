const {readFileSync} = require('node:fs');
const {runInNewContext} = require('node:vm');
const assert = require('node:assert/strict');
const select = {value: '', addEventListener: (_, fn) => { select.change = fn; }};
const confirmation = {checked: true};
const hint = {hidden: false};
const panels = ['local_pickup:27', 'gls_shipping_method:0'].map(key => ({dataset: {reviewChoice: key}, hidden: false}));
const form = {querySelector: key => key.includes('shipping_choice') ? select : key.includes('confirm_review') ? confirmation : hint, querySelectorAll: () => panels};
const document = {querySelectorAll: () => [form, {querySelector: () => null}]};
runInNewContext(readFileSync(process.argv[2] || __dirname + '/../assets/review-preview.js', 'utf8'), {document});
assert.deepEqual(panels.map(p => p.hidden), [true, true]);
assert.equal(hint.hidden, false);
select.value = 'gls_shipping_method:0'; select.change();
assert.deepEqual(panels.map(p => p.hidden), [true, false]);
assert.equal(confirmation.checked, false);
assert.equal(hint.hidden, true);
confirmation.checked = true; select.value = 'local_pickup:27'; select.change();
assert.deepEqual(panels.map(p => p.hidden), [false, true]);
assert.equal(confirmation.checked, false);
select.value = ''; select.change();
assert.deepEqual(panels.map(p => p.hidden), [true, true]);
assert.equal(hint.hidden, false);
console.log('Back Office review preview: 9 assertions passed; no network or order mutation.');
